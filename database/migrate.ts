require('dotenv').config();
const path = require('path');
const fs = require('fs');
const db = require('./database.js');

const patternFolderPath = process.env["PATTERN_FOLDER_PATH"] || 'C:/Users/louca/Documents/PatternFolder';
const patternIndexPath = path.join(patternFolderPath, 'patternIndex.json');

console.log('Starting migration from JSON to SQLite database...\n');

// Check if JSON file exists
if (!fs.existsSync(patternIndexPath)) {
  console.log('❌ No patternIndex.json file found at:', patternIndexPath);
  console.log('Nothing to migrate.');
  process.exit(0);
}

try {
  // Read the JSON file
  const patternsJSON = fs.readFileSync(patternIndexPath, 'utf-8');
  const patterns = JSON.parse(patternsJSON);
  
  console.log(`📁 Found ${patterns.length} patterns in JSON file\n`);
  
  if (patterns.length === 0) {
    console.log('No patterns to migrate.');
    process.exit(0);
  }
  
  // Migrate each pattern
  let successCount = 0;
  let errorCount = 0;
  
  patterns.forEach((pattern: any, index: number) => {
    try {
      // Prepare pattern data with all required fields
      const patternData = {
        id: 0, // Will be auto-generated by database
        name: pattern.name,
        brand: pattern.brand || null,
        difficulty: pattern.difficulty || 1,
        category: pattern.category,
        description: pattern.description || '',
        photos: pattern.photos || [],
        techDrawings: pattern.techDrawings || [],
        files: pattern.files || [],
        comments: pattern.comments || []
      };
      
      // Insert into database
      db.addPattern(patternData);
      successCount++;
      console.log(`✅ [${index + 1}/${patterns.length}] Migrated: ${pattern.name}`);
      
    } catch (err) {
      errorCount++;
      console.error(`❌ [${index + 1}/${patterns.length}] Error migrating "${pattern.name}":`, (err as Error).message);
    }
  });
  
  console.log('\n--- Migration Summary ---');
  console.log(`✅ Successfully migrated: ${successCount} patterns`);
  if (errorCount > 0) {
    console.log(`❌ Failed: ${errorCount} patterns`);
  }
  
  // Backup the old JSON file
  if (successCount > 0) {
    const backupPath = path.join(patternFolderPath, 'patternIndex.json.backup');
    fs.renameSync(patternIndexPath, backupPath);
    console.log(`\n📦 Original JSON file backed up to: ${backupPath}`);
    console.log('✨ Migration completed successfully!');
  }
  
} catch (error) {
  console.error('❌ Migration failed:', (error as Error).message);
  console.error(error);
  process.exit(1);
}
